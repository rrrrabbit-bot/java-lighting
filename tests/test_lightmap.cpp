#include "lighting/JavaLightmap.h"

#include <array>
#include <cstdio>
#include <cstdint>

namespace {

int failures = 0;

void expectEq(long long got, long long want, char const* what) {
    if (got != want) {
        std::printf("FAIL %s: got %lld, want %lld\n", what, got, want);
        ++failures;
    }
}

void expectRgb(std::array<uint8_t, 3> const& got, std::array<uint8_t, 3> const& want, char const* what) {
    if (got != want) {
        std::printf(
            "FAIL %s: got #%02X%02X%02X, want #%02X%02X%02X\n",
            what,
            got[0],
            got[1],
            got[2],
            want[0],
            want[1],
            want[2]
        );
        ++failures;
    }
}

/// Legacy (MC 1.20.1) arithmetic applied the 0.04 grey mix twice. The C++ port
/// follows the canonical 1.21.4 shader (single mix), so the oracle values below
/// are for the shader variant: they were generated by tools/gen_reference.py
/// (see tests/expected_lightmap.json).
std::array<std::array<uint8_t, 3>, 256> table(float skyDarken, float gamma) {
    java_lighting::LightmapSettings s;
    s.gamma     = gamma;
    s.skyDarken = skyDarken;
    return java_lighting::JavaLightmap::buildTableU8(s);
}

std::array<uint8_t, 3> at(std::array<std::array<uint8_t, 3>, 256> const& t, int sky, int block) {
    return t[static_cast<size_t>(sky * 16 + block)];
}

} // namespace

int main() {
    using java_lighting::JavaLightmap;

    // 1. Sanity: 256 cells, morning table matches Java's shape.
    auto day = table(1.0f, 0.5f);
    expectRgb(at(day, 0, 0), {25, 25, 25}, "day (sky0,block0) == #191919");
    expectRgb(at(day, 15, 15), {252, 252, 252}, "day (sky15,block15) == #FCFCFC-ish");

    // 2. Warm block light: red > green > blue for mid block light with no sky.
    auto cell = at(day, 0, 6);
    if (!(cell[0] > cell[1] && cell[1] > cell[2])) {
        std::printf("FAIL block light is not warm: %u %u %u\n", cell[0], cell[1], cell[2]);
        ++failures;
    }

    // 3. Night sky light is blue, noon sky light is neutral.
    auto night = table(0.2f, 0.5f);
    auto nightSky = at(night, 15, 0);
    if (!(nightSky[2] > nightSky[0] + 30)) {
        std::printf("FAIL night sky light is not blue: %u %u %u\n", nightSky[0], nightSky[1], nightSky[2]);
        ++failures;
    }
    auto daySky = at(day, 15, 0);
    if (daySky[0] != daySky[2]) {
        std::printf("FAIL day sky light is not neutral: %u %u %u\n", daySky[0], daySky[1], daySky[2]);
        ++failures;
    }

    // 4. Brightness (gamma) lifts shadows monotonically.
    auto g0 = table(1.0f, 0.0f);
    auto g1 = table(1.0f, 1.0f);
    if (!(at(g0, 0, 0)[0] < at(g1, 0, 0)[0])) {
        std::printf("FAIL gamma does not lift dark pixels\n");
        ++failures;
    }

    // 5. Deterministic checksum (FNV-1a 64) for regression against the Python
    //    reference in tests/expected_lightmap.json (generated by
    //    tools/gen_reference.py). If the algorithm changes, this fails loudly.
    uint64_t const dayChecksum = JavaLightmap::tableChecksum(day);
    std::printf("day checksum:   0x%016llX\n", static_cast<unsigned long long>(dayChecksum));
    std::printf("night checksum: 0x%016llX\n", static_cast<unsigned long long>(JavaLightmap::tableChecksum(night)));
    expectEq(
        static_cast<long long>(dayChecksum),
        static_cast<long long>(0x225C4263708D2897ull),
        "day table FNV-1a checksum"
    );
    expectEq(
        static_cast<long long>(JavaLightmap::tableChecksum(night)),
        static_cast<long long>(0x23FC6AB5296F0BD6ull),
        "night table FNV-1a checksum"
    );

    if (failures == 0) {
        std::printf("All JavaLightmap checks passed.\n");
        return 0;
    }
    std::printf("%d check(s) failed.\n", failures);
    return 1;
}
